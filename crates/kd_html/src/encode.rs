/// Finds, in one pass as the parser of a browser reads the page, the text where a
/// character reference is text ([`Layout::raw`]) and the `<meta>` tags. `lower` is `html`
/// in lower case.
///
/// - The text of a `<script>` ends only at its `</script`, so a `<style>` inside it (in a
///   string, say) is text and does not start a range of its own; a `<meta>` there is text
///   too. So are `<style>`, `<xmp>`, `<iframe>`, `<noembed>`, `<noframes>` and
///   `<plaintext>` (to the end of the page). The text of a `<title>` and a `<textarea>`
///   reads references, and the tags written in it are text as well.
/// - A `<noscript>` is read as a browser without scripts reads it, as HTML: that is the
///   only one that shows it.
/// - A comment (`<!--` to `-->`), a doctype and a quoted attribute value are passed over:
///   a `<script>` written there starts nothing.
/// - Inside `<svg>` and `<math>`, a `<style>` and a `<script>` are not ranges, and a CDATA
///   section is one. An integration point (`<foreignObject>`, `<desc>` and `<title>` of
///   SVG; `<mi>`, `<mo>`, `<mn>`, `<ms>`, `<mtext>` and an `<annotation-xml>` of HTML of
///   MathML) holds HTML again, and a tag of [`BREAKOUT`] ends foreign content.
fn layout(html: &str, lower: &str) -> Layout {
	let bytes = lower.as_bytes();
	let mut layout = Layout::default();
	// The elements that changed what their tags are, the innermost last, with what they
	// are in them: `<svg>` and `<math>`, the integration points in them, and the
	// `<annotation-xml>` of MathML, whose `<svg>` is SVG.
	let mut open: Vec<(&str, Namespace)> = Vec::new();
	let mut from = 0;
	while let Some(found) = lower[from..].find('<') {
		let start = from + found;
		let rest = &lower[start..];
		let namespace = open.last().map_or(Namespace::Html, |&(_, ns)| ns);
		if rest.starts_with("<!--") {
			from = comment_end(lower, start + 4);
			continue;
		}
		// Only in upper case, as the standard reads it.
		if namespace != Namespace::Html && html[start..].starts_with("<![CDATA[") {
			let text_start = start + 9;
			let text_end = lower[text_start..]
				.find("]]>")
				.map_or(lower.len(), |i| text_start + i);
			layout.raw.push((text_start, text_end));
			from = (text_end + 3).min(lower.len());
			continue;
		}
		// A doctype, and what the parser reads as a comment (`<![CDATA[` in HTML, `<?xml`).
		if rest.starts_with("<!") || rest.starts_with("<?") {
			from = lower[start..]
				.find('>')
				.map_or(lower.len(), |i| start + i + 1);
			continue;
		}
		let closing = rest.starts_with("</");
		let name_start = start + if closing { 2 } else { 1 };
		// `a < b` is text.
		if !bytes.get(name_start).is_some_and(u8::is_ascii_alphabetic) {
			from = start + 1;
			continue;
		}
		let name_end = (name_start..bytes.len())
			.find(|&i| ends_a_tag_name(bytes, i))
			.unwrap_or(bytes.len());
		let name = &lower[name_start..name_end];
		let gt = tag_end(bytes, name_end);
		if gt == bytes.len() {
			break;
		}
		from = gt + 1;
		if closing {
			if namespace != Namespace::Html && matches!(name, "br" | "p") {
				leave_foreign(&mut open);
				continue;
			}
			// Closes the element of that name, but not across an integration point: the
			// browser ignores a `</svg>` inside a `<foreignObject>`.
			for i in (0..open.len()).rev() {
				if open[i].0 == name {
					open.truncate(i);
					break;
				}
				if open[i].1 == Namespace::Html {
					break;
				}
			}
			continue;
		}
		let attributes = &lower[name_end..gt];
		let self_closing = attributes.ends_with('/');
		let mut namespace = namespace;
		if namespace != Namespace::Html && is_breakout(name, attributes) {
			leave_foreign(&mut open);
			namespace = open.last().map_or(Namespace::Html, |&(_, ns)| ns);
		}
		if namespace != Namespace::Html {
			if self_closing {
				continue;
			}
			if is_integration_point(namespace, name, attributes) {
				open.push((name, Namespace::Html));
			} else if name == "annotation-xml" {
				open.push((name, namespace));
			} else if name == "svg"
				&& open
					.last()
					.is_some_and(|&(open, _)| open == "annotation-xml")
			{
				open.push((name, Namespace::Svg));
			} else if matches!(name, "svg" | "math") {
				// An element of the same language (an `<svg>` in an `<svg>`), counted so
				// that its end tag does not close the outer one.
				open.push((name, namespace));
			}
			continue;
		}
		match name {
			"svg" if !self_closing => open.push((name, Namespace::Svg)),
			"math" if !self_closing => open.push((name, Namespace::MathMl)),
			"meta" => layout.meta_tags.push((name_end, gt)),
			"plaintext" => {
				layout.raw.push((gt + 1, lower.len()));
				break;
			}
			"script" | "style" | "xmp" | "iframe" | "noembed" | "noframes" | "title"
			| "textarea" => {
				let text_start = gt + 1;
				let text_end = end_tag(lower, text_start, name);
				if !matches!(name, "title" | "textarea") {
					layout.raw.push((text_start, text_end));
				}
				from = text_end;
			}
			_ => {}
		}
	}
	layout
}

/// Where the text of an element of raw text that starts at `from` ends: at its end tag
/// (`</script`, but not `</scripts`), or at the end of the text.
fn end_tag(lower: &str, from: usize, name: &str) -> usize {
	let bytes = lower.as_bytes();
	let mut at = from;
	while let Some(found) = lower[at..].find("</") {
		let start = at + found;
		let name_end = start + 2 + name.len();
		if lower[start + 2..].starts_with(name) && ends_a_tag_name(bytes, name_end) {
			return start;
		}
		at = start + 2;
	}
	lower.len()
}

/// Where a comment whose text starts at `from` ends: after its `-->` (or `--!>`, or the
/// `>` of `<!-->` and `<!--->`), or at the end of the text when it is not closed.
fn comment_end(lower: &str, from: usize) -> usize {
	let rest = &lower[from..];
	if rest.starts_with('>') {
		return from + 1;
	}
	if rest.starts_with("->") {
		return from + 2;
	}
	[("-->", 3), ("--!>", 4)]
		.into_iter()
		.filter_map(|(close, len)| rest.find(close).map(|at| (at, len)))
		.min()
		.map_or(lower.len(), |(at, len)| from + at + len)
}

/// Closes the elements of `<svg>` and `<math>` up to the HTML around them.
fn leave_foreign(open: &mut Vec<(&str, Namespace)>) {
	while open.last().is_some_and(|&(_, ns)| ns != Namespace::Html) {
		open.pop();
	}
}

/// Whether a start tag in foreign content ends it ([`BREAKOUT`]).
fn is_breakout(name: &str, attributes: &str) -> bool {
	BREAKOUT.contains(&name)
		|| name == "font"
			&& attribute_values(attributes)
				.any(|(attribute, _)| matches!(attribute, "color" | "face" | "size"))
}

/// Whether an element of `<svg>` or `<math>` holds HTML.
fn is_integration_point(namespace: Namespace, name: &str, attributes: &str) -> bool {
	match (namespace, name) {
		(Namespace::Svg, "foreignobject" | "desc" | "title")
		| (Namespace::MathMl, "mi" | "mo" | "mn" | "ms" | "mtext") => true,
		(Namespace::MathMl, "annotation-xml") => {
			attribute_values(attributes).any(|(attribute, value)| {
				attribute == "encoding" && matches!(value, "text/html" | "application/xhtml+xml")
			})
		}
		_ => false,
	}
}

/// The names and values of the attributes written in `attributes` (the part of a start tag
/// after its name, without the `>`). A value that is not written is empty.
fn attribute_values(attributes: &str) -> impl Iterator<Item = (&str, &str)> {
	let bytes = attributes.as_bytes();
	let mut i = 0;
	std::iter::from_fn(move || {
		while bytes
			.get(i)
			.is_some_and(|b| b.is_ascii_whitespace() || *b == b'/')
		{
			i += 1;
		}
		if i >= bytes.len() {
			return None;
		}
		let start = i;
		while bytes
			.get(i)
			.is_some_and(|b| !b.is_ascii_whitespace() && *b != b'/' && *b != b'=')
		{
			i += 1;
		}
		let name = &attributes[start..i];
		let mut j = i;
		while bytes.get(j).is_some_and(u8::is_ascii_whitespace) {
			j += 1;
		}
		if bytes.get(j) != Some(&b'=') {
			return Some((name, ""));
		}
		j += 1;
		while bytes.get(j).is_some_and(u8::is_ascii_whitespace) {
			j += 1;
		}
		let value = match bytes.get(j) {
			Some(&quote @ (b'"' | b'\'')) => {
				let end = bytes[j + 1..]
					.iter()
					.position(|&b| b == quote)
					.map_or(bytes.len(), |at| j + 1 + at);
				i = (end + 1).min(bytes.len());
				&attributes[j + 1..end]
			}
			_ => {
				let end = bytes[j..]
					.iter()
					.position(u8::is_ascii_whitespace)
					.map_or(bytes.len(), |at| j + at);
				i = end;
				&attributes[j..end]
			}
		};
		Some((name, value))
	})
}

/// Encodes `html` as the bytes to write.
///
/// # Example
///
/// ```
/// use kd_html::encode::{encode, Encoding};
///
/// assert_eq!(encode("日本", Encoding::Utf8), "日本".as_bytes());
/// // Shift_JIS: two bytes for each of the two characters.
/// assert_eq!(encode("日本", Encoding::ShiftJis), [0x93, 0xFA, 0x96, 0x7B]);
/// // What it cannot hold becomes a character reference.
/// assert_eq!(encode("© 〜", Encoding::ShiftJis), b"&copy; &#12316;");
/// ```
#[must_use]
pub fn encode(html: &str, encoding: Encoding) -> Vec<u8> {
	encode_reporting(html, encoding).0
}

/// Like [`encode`], and also the characters that became `?` because the encoding has none
/// of them and a character reference would be read as text there (inside `<script>` and
/// `<style>` of HTML, as the module says): each one once, in the order of first appearance. A character that became a
/// reference is not in the list: the page still says what it said.
///
/// # Example
///
/// ```
/// use kd_html::encode::{encode_reporting, Encoding};
///
/// let (bytes, replaced) = encode_reporting("<p>〜</p><script>a = '〜〜⚠'</script>", Encoding::ShiftJis);
/// assert_eq!(bytes, b"<p>&#12316;</p><script>a = '???'</script>");
/// assert_eq!(replaced, ['〜', '⚠']);
/// ```
#[must_use]
pub fn encode_reporting(html: &str, encoding: Encoding) -> (Vec<u8>, Vec<char>) {
	match encoding {
		Encoding::Utf8 => (html.as_bytes().to_vec(), Vec::new()),
		Encoding::ShiftJis => to_shift_jis(html),
	}
}

fn to_shift_jis(html: &str) -> (Vec<u8>, Vec<char>) {
	// Longer than the names it replaces (`utf-8`, `utf8`), so the ranges only move forward.
	const CHARSET: &str = "shift_jis";
	if html.is_ascii()
		&& !html
			.as_bytes()
			.windows(5)
			.any(|w| w.eq_ignore_ascii_case(b"<meta"))
	{
		return (html.as_bytes().to_vec(), Vec::new());
	}
	let lower = html.to_ascii_lowercase();
	let Layout { mut raw, meta_tags } = layout(html, &lower);
	let rewritten;
	let html = if meta_tags.is_empty() {
		html
	} else {
		let edits;
		(rewritten, edits) = rewrite_meta_charset(html, &lower, &meta_tags, CHARSET);
		// The names of the encoding are outside the ranges; each one before a range moves it.
		let mut delta = 0;
		let mut next_edit = 0;
		for range in &mut raw {
			while next_edit < edits.len() && edits[next_edit].0 < range.0 {
				delta += CHARSET.len() - edits[next_edit].1;
				next_edit += 1;
			}
			range.0 += delta;
			range.1 += delta;
		}
		rewritten.as_str()
	};
	let mut out = Vec::with_capacity(html.len());
	let mut replaced = Vec::new();
	// What `replaced` holds, for the test of a character that was seen already.
	let mut seen = HashSet::new();
	let mut next_raw = 0;
	let mut buf = [0u8; 4];
	for (at, c) in html.char_indices() {
		if c.is_ascii() {
			out.push(c as u8);
			continue;
		}
		if let Some((bytes, n)) = shift_jis_of(c) {
			out.extend_from_slice(&bytes[..n]);
			continue;
		}
		while next_raw < raw.len() && raw[next_raw].1 <= at {
			next_raw += 1;
		}
		if next_raw < raw.len() && raw[next_raw].0 <= at {
			out.push(b'?');
			if seen.insert(c) {
				replaced.push(c);
			}
			continue;
		}
		match name_of(c.encode_utf8(&mut buf)) {
			Some(name) => {
				out.push(b'&');
				out.extend_from_slice(name.as_bytes());
				out.push(b';');
			}
			None => out.extend_from_slice(format!("&#{};", c as u32).as_bytes()),
		}
	}
	(out, replaced)
}

