//! The bytes of a page in the character encoding it is delivered in.
//!
//! A site that is still served as Shift_JIS (an older Japanese site, say) writes its pages in UTF-8 and
//! has them converted when they are written. This does what d-zero/builder did with
//! `charset: { encoding: 'shift_jis' }`:
//!
//! - the encoding a `<meta>` names (`charset="utf-8"`, or the `charset=` of a `content`)
//!   becomes `shift_jis`;
//! - the text is encoded as Windows Shift_JIS (CP932, what `iconv-lite` calls `CP932`);
//! - a character that the encoding cannot hold is written as a character reference, its
//!   name (`&copy;`) when it has one and its number (`&#12316;`) when not, so that nothing is
//!   lost and the browser shows the same text. Inside `<script>` and `<style>` a reference
//!   would be read as text, so there the character becomes `?` (what `iconv-lite` writes),
//!   and so it does in the other elements of raw text (`<xmp>`, `<iframe>`, …). Those of
//!   `<svg>` and `<math>` read references, as the browser does, and get them; a CDATA
//!   section there does not, and gets `?`.
//!
//! The table of two-byte characters is generated by `scripts/gen-cp932-table.mjs`.

use std::collections::{HashMap, HashSet};
use std::sync::OnceLock;

use crate::cp932_table::{DOUBLE, TRAILS};
use crate::entities::name_of;

/// The encoding a page is written in.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Encoding {
	/// UTF-8, as it is.
	#[default]
	Utf8,
	/// Windows Shift_JIS (CP932).
	ShiftJis,
}

/// What an encoded character is, by code point.
fn reverse() -> &'static HashMap<u16, u16> {
	static TABLE: OnceLock<HashMap<u16, u16>> = OnceLock::new();
	TABLE.get_or_init(|| {
		let mut map = HashMap::with_capacity(DOUBLE.len());
		for (pointer, &cp) in DOUBLE.iter().enumerate() {
			// The pointers of the NEC-selected IBM extensions are left to the IBM ones
			// (the WHATWG encoder does the same, and so does Microsoft).
			if cp == 0 || (8272..=8835).contains(&pointer) {
				continue;
			}
			let lead = pointer / TRAILS;
			let trail = pointer % TRAILS;
			let lead_byte = if lead < 31 { 0x81 + lead } else { 0xC1 + lead };
			let trail_byte = if trail < 63 {
				0x40 + trail
			} else {
				0x41 + trail
			};
			map.entry(cp)
				.or_insert(((lead_byte << 8) | trail_byte) as u16);
		}
		map
	})
}

/// The bytes of one character, or `None` when Shift_JIS has none for it.
fn shift_jis_of(c: char) -> Option<([u8; 2], usize)> {
	let cp = c as u32;
	match cp {
		0..=0x80 => Some(([cp as u8, 0], 1)),
		// The yen sign and the overline are the backslash and the tilde of JIS X 0201.
		0xA5 => Some(([0x5C, 0], 1)),
		0x203E => Some(([0x7E, 0], 1)),
		// Half-width katakana.
		0xFF61..=0xFF9F => Some((([(cp - 0xFF61 + 0xA1) as u8, 0]), 1)),
		// The private use area is not a part of CP932 for `iconv-lite`.
		0xE000..=0xF8FF => None,
		0x81..=0xFFFF => reverse()
			.get(&(cp as u16))
			.map(|&b| (([(b >> 8) as u8, (b & 0xFF) as u8]), 2)),
		_ => None,
	}
}

/// Names `charset` where a `<meta>` says the page is UTF-8: the `charset` attribute
/// (`<meta charset="utf-8">`, quoted either way or not at all) and the `charset=` of a
/// `content` (`<meta http-equiv="Content-Type" content="text/html; charset=utf-8">`), in
/// any case and whatever other attributes the tag has. Only the name of the encoding is
/// replaced; the rest of the tag stays as it was written.
///
/// `meta_tags` are the attributes of the `<meta>` tags that [`layout`] found, so a `<meta>` in a
/// comment or in the text of a `<script>` (a string of the JS) is left as it is. Also gives
/// where each replaced name was and how long it was, to move the offsets that follow it.
fn rewrite_meta_charset(
	html: &str,
	lower: &str,
	meta_tags: &[(usize, usize)],
	charset: &str,
) -> (String, Vec<(usize, usize)>) {
	let bytes = lower.as_bytes();
	let mut out = String::with_capacity(html.len());
	let mut edits = Vec::new();
	let mut last = 0;
	for &(after, end) in meta_tags {
		let mut i = after;
		while let Some(found) = lower[i..end].find("charset") {
			let at = i + found;
			i = at + 7;
			// Not the end of another name (`data-charset`): after a space, a quote or `;`.
			if !(bytes[at - 1].is_ascii_whitespace()
				|| matches!(bytes[at - 1], b'"' | b'\'' | b';'))
			{
				continue;
			}
			let mut j = at + 7;
			while bytes.get(j).is_some_and(u8::is_ascii_whitespace) {
				j += 1;
			}
			if bytes.get(j) != Some(&b'=') {
				continue;
			}
			j += 1;
			while bytes.get(j).is_some_and(u8::is_ascii_whitespace) {
				j += 1;
			}
			if matches!(bytes.get(j), Some(b'"' | b'\'')) {
				j += 1;
			}
			let name = if lower[j..end].starts_with("utf-8") {
				5
			} else if lower[j..end].starts_with("utf8") {
				4
			} else {
				continue;
			};
			// The name ends there: a longer one (`utf-8x`) is another name.
			if bytes
				.get(j + name)
				.is_some_and(|b| b.is_ascii_alphanumeric() || *b == b'-' || *b == b'_')
			{
				continue;
			}
			out.push_str(&html[last..j]);
			out.push_str(charset);
			edits.push((j, name));
			last = j + name;
			i = last;
		}
	}
	out.push_str(&html[last..]);
	(out, edits)
}

/// Where the tag that has its attributes from `from` ends: its `>`, or the end of the text.
///
/// As in the HTML standard, a quote starts a value only right after an `=`, and a `>` in the
/// quoted value does not end the tag; a quote in a name or in a value that is not quoted
/// (`data-x=don't`) is a character like the others.
fn tag_end(bytes: &[u8], from: usize) -> usize {
	let mut i = from;
	while let Some(&b) = bytes.get(i) {
		match b {
			b'>' => return i,
			b'=' => {
				i += 1;
				while bytes.get(i).is_some_and(u8::is_ascii_whitespace) {
					i += 1;
				}
				if let Some(&quote @ (b'"' | b'\'')) = bytes.get(i) {
					let Some(at) = bytes[i + 1..].iter().position(|&b| b == quote) else {
						return bytes.len();
					};
					i += at + 2;
				} else {
					while bytes
						.get(i)
						.is_some_and(|&b| !b.is_ascii_whitespace() && b != b'>')
					{
						i += 1;
					}
				}
			}
			_ => i += 1,
		}
	}
	bytes.len()
}

/// Whether the name of a tag ends at `at`: what follows it is a space, `/` or `>`.
fn ends_a_tag_name(bytes: &[u8], at: usize) -> bool {
	bytes
		.get(at)
		.is_some_and(|&b| b.is_ascii_whitespace() || b == b'/' || b == b'>')
}

/// What the scan of a page finds, as byte offsets.
#[derive(Debug, Default, PartialEq, Eq)]
struct Layout {
	/// The text where a character reference is not one but text, in order and apart from
	/// each other: that of a `<script>`, a `<style>` and the other elements of raw text of
	/// HTML, and a CDATA section in `<svg>` or `<math>`.
	raw: Vec<(usize, usize)>,
	/// The attributes of each `<meta>` tag: from the end of its name to its `>`.
	meta_tags: Vec<(usize, usize)>,
}

/// What the tags in an element are: HTML, or those of `<svg>` or `<math>` (foreign
/// content). In foreign content a `<style>` or a `<script>` is an element like any other,
/// whose text reads character references.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Namespace {
	Html,
	Svg,
	MathMl,
}

/// The tags of HTML that end foreign content where they start (the list of the HTML
/// standard, "parsing main inforeign"); `<font>` is one only with `color`, `face` or `size`.
