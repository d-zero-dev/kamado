/**
 * Writes the tables of `kd_css`:
 *
 * - `crates/kd_css/src/color_table.rs`: the colour names cssnano's colormin
 *   knows (the table of `@colordx/core/plugins/names`: the 148 CSS names minus
 *   `transparent` and the `grey` spellings, which colordx does not parse), in
 *   the table's own order, because the first name of a colour wins (`aqua`
 *   before `cyan`);
 * - `crates/kd_css/src/property_table.rs`: the property names whose values the
 *   minifier rewrites (the properties of `mdn-data`, the descriptors of
 *   at-rules, SVG presentation properties and the vendor extensions that are
 *   still written, all without their vendor prefix). A value of any other
 *   property only loses white space.
 *
 * colordx is the one cssnano's colormin resolves (not pinned, like the rest of
 * what cssnano pulls in: `docs/v3/development.md`, "v2 の oracle"). mdn-data is
 * pinned in the root `devDependencies`: cssnano rewrites the value of every
 * property and reads no list of them, so the list is ours to declare. A name
 * that a later mdn-data drops goes into `extras`, so that it stays known (an
 * unknown property keeps its value, which widens the difference from
 * cssnano).
 *
 * Run it when colordx or mdn-data is upgraded: `node scripts/generate-css-tables.mjs`.
 * `scripts/generate-css-tables.spec.ts` fails while the committed tables are not
 * what it writes.
 */
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const require = createRequire(import.meta.url);
const outDir = path.join(root, 'crates', 'kd_css', 'src');

/**
 * Reads what the tables are made from, out of `node_modules`.
 * @returns {{ colorNames: string, mdnData: { version: string, properties: Record<string, unknown> } }}
 * `colorNames` is the source of `@colordx/core/plugins/names`
 * @example
 * const { mdnData } = readSources();
 * mdnData.version; // the installed version, as package.json declares it
 */
export function readSources() {
	const names = require.resolve('@colordx/core/plugins/names');
	return {
		colorNames: readFileSync(names.replace(/\.cjs$/u, '.mjs'), 'utf8'),
		mdnData: {
			version: require('mdn-data/package.json').version,
			properties: require('mdn-data/css/properties.json'),
		},
	};
}

/**
 * The `[name, '#rrggbb']` pairs of colordx's table, in its order.
 * @param {string} source - The source of `@colordx/core/plugins/names`
 * @returns {[string, string][]}
 * @example
 * readColorNames('var e={aqua:"#00ffff"}'); // [['aqua', '#00ffff']]
 */
export function readColorNames(source) {
	const match = /var e=(\{[^}]*\})/u.exec(source);
	if (!match) {
		throw new Error('cannot find the colour table in @colordx/core/plugins/names');
	}
	return Object.entries(new Function(`return ${match[1]}`)());
}

/**
 * The text of `color_table.rs`.
 * @param {readonly (readonly [string, string])[]} entries - From {@link readColorNames}
 * @returns {string}
 * @example
 * renderColorTable([['aqua', '#00ffff']]);
 * // a table of 1 name: ("aqua", 0x00ffff)
 */
export function renderColorTable(entries) {
	let out = `//! Generated by \`scripts/generate-css-tables.mjs\`; do not edit.\n\n`;
	out += `/// The colour names colormin knows with their \`0xRRGGBB\` values, in the order\n`;
	out += `/// of the table it uses (sorted by name).\n`;
	out += `pub const COLOR_NAMES: [(&str, u32); ${entries.length}] = [\n`;
	for (const [name, hex] of entries) {
		out += `\t("${name}", 0x${hex.slice(1)}),\n`;
	}
	out += `];\n`;
	return out;
}

