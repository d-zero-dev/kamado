/**
 * Writes `crates/kd_css/src/color_table.rs`: the colour names cssnano's
 * colormin knows (the table of `@colordx/core/plugins/names`: the 148 CSS
 * names minus `transparent` and the `grey` spellings, which colordx does not
 * parse), in the table's own order, because the first name of a colour wins
 * (`aqua` before `cyan`). Run it when colordx is upgraded:
 * `node scripts/generate-css-tables.mjs`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const require = createRequire(import.meta.url);
const names = require.resolve('@colordx/core/plugins/names');
const source = readFileSync(names.replace(/\.cjs$/u, '.mjs'), 'utf8');
const match = /var e=(\{[^}]*\})/u.exec(source);
if (!match) {
	throw new Error('cannot find the colour table in @colordx/core/plugins/names');
}
const table = Function(`return ${match[1]}`)();
const entries = Object.entries(table);

let out = `//! Generated by \`scripts/generate-css-tables.mjs\`; do not edit.\n\n`;
out += `/// The colour names colormin knows with their \`0xRRGGBB\` values, in the order\n`;
out += `/// of the table it uses (sorted by name).\n`;
out += `pub const COLOR_NAMES: [(&str, u32); ${entries.length}] = [\n`;
for (const [name, hex] of entries) {
	out += `\t("${name}", 0x${hex.slice(1)}),\n`;
}
out += `];\n`;
writeFileSync(path.join(root, 'crates', 'kd_css', 'src', 'color_table.rs'), out);
process.stdout.write(`wrote ${entries.length} colour names\n`);
