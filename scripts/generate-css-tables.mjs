/**
 * The known property names: those of mdn-data and `extras`, without their
 * vendor prefix, sorted (the table is searched by bisection).
 * @param {Record<string, unknown>} properties - `mdn-data/css/properties.json`
 * @returns {string[]}
 * @example
 * knownProperties({ '-webkit-box-flex': {} }).includes('box-flex'); // true
 */
export function knownProperties(properties) {
	const prefix = /^-(?:webkit|moz|ms|o|khtml|apple|epub)-/u;
	const known = new Set(
		[...Object.keys(properties), ...extras].map((p) => p.replace(prefix, '')),
	);
	return [...known].toSorted();
}

/**
 * The text of `property_table.rs`.
 * @param {readonly string[]} names - From {@link knownProperties}
 * @param {string} version - The version of mdn-data
 * @returns {string}
 * @example
 * renderPropertyTable(['color'], readSources().mdnData.version);
 * // a table of 1 name, with the version of mdn-data it was made from
 */
export function renderPropertyTable(names, version) {
	let props = `//! Generated by \`scripts/generate-css-tables.mjs\`; do not edit.\n`;
	props += `//! Source: the properties of mdn-data ${version} and the generator's \`extras\`.\n\n`;
	props += `/// The properties (and descriptors) whose values are rewritten, sorted, without\n`;
	props += `/// vendor prefixes.\n`;
	props += `pub const KNOWN_PROPERTIES: [&str; ${names.length}] = [\n`;
	for (const p of names) {
		props += `\t"${p}",\n`;
	}
	props += `];\n`;
	return props;
}

// Node resolves the main module through symbolic links, `argv[1]` keeps the path
// as given.
if (process.argv[1] && realpathSync(process.argv[1]) === import.meta.filename) {
	const { colorNames, mdnData } = readSources();
	const colors = readColorNames(colorNames);
	writeFileSync(path.join(outDir, 'color_table.rs'), renderColorTable(colors));
	process.stdout.write(`wrote ${colors.length} colour names\n`);
	const names = knownProperties(mdnData.properties);
	writeFileSync(
		path.join(outDir, 'property_table.rs'),
		renderPropertyTable(names, mdnData.version),
	);
	process.stdout.write(
		`wrote ${names.length} property names (mdn-data ${mdnData.version})\n`,
	);
}
