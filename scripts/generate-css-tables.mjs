// mdn-data is the property list of cssnano's own toolchain (a transitive
// dependency); this generator only reads it to write a table.
// eslint-disable-next-line import-x/no-extraneous-dependencies
const properties = require('mdn-data/css/properties.json');
const prefix = /^-(?:webkit|moz|ms|o|khtml|apple|epub)-/u;
const known = new Set(
	[...Object.keys(properties), ...extras].map((p) => p.replace(prefix, '')),
);
const sorted = [...known].toSorted();
let props = `//! Generated by \`scripts/generate-css-tables.mjs\`; do not edit.\n\n`;
props += `/// The properties (and descriptors) whose values are rewritten, sorted, without\n`;
props += `/// vendor prefixes.\n`;
props += `pub const KNOWN_PROPERTIES: [&str; ${sorted.length}] = [\n`;
for (const p of sorted) {
	props += `\t"${p}",\n`;
}
props += `];\n`;
writeFileSync(path.join(outDir, 'property_table.rs'), props);
process.stdout.write(`wrote ${sorted.length} property names\n`);
