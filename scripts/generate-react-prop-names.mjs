/**
 * Generates `scripts/react-prop-names.mjs`: how React spells the attributes that Pug
 * writes in lower case (`datetime` → `dateTime`, `srcset` → `srcSet`), for
 * `pug-to-tsx.mjs`. The types of `@types/react` know only the React spelling, and
 * a page written with it type-checks.
 *
 * The names are read out of the `possibleStandardNames` map of the installed react-dom's
 * development build (the one React itself uses to tell a misspelt attribute), as text;
 * nothing is probed by rendering. The names that React writes the same as the HTML
 * attribute, and the event handlers (`on*`, which take a function), are left out.
 *
 * Run it when react-dom is upgraded: `node scripts/generate-react-prop-names.mjs`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, 'node_modules', 'react-dom');
const output = path.join(import.meta.dirname, 'react-prop-names.mjs');

/**
 * The `[HTML attribute, React prop]` pairs, sorted, where the two differ.
 * @param {string} source - `react-dom-server.node.development.js`
 * @returns {[string, string][]}
 * @example
 * readPropNames('possibleStandardNames = {\n  datetime: "dateTime",\n  alt: "alt",\n      },');
 * // [['datetime', 'dateTime']]
 */
export function readPropNames(source) {
	const start = source.indexOf('possibleStandardNames = {');
	if (start === -1) {
		throw new Error('possibleStandardNames not found in react-dom');
	}
	// The map is one of a chain of declarations, so it ends with `},`.
	const end = source.indexOf('\n      },', start);
	if (end === -1) {
		throw new Error('the end of possibleStandardNames not found in react-dom');
	}
	/** @type {Map<string, string>} */
	const names = new Map();
	for (const line of source.slice(start, end).split('\n').slice(1)) {
		const match = /^\s+"?([A-Z0-9:-]+)"?: "([A-Z0-9]+)",?$/i.exec(line);
		if (!match) {
			throw new Error(
				`a line of possibleStandardNames is not understood: ${line.trim()}`,
			);
		}
		const [, attribute, prop] = match;
		if (attribute !== prop && !attribute.startsWith('on')) {
			names.set(attribute, prop);
		}
	}
	return [...names].toSorted(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

/**
 * The text of the generated module.
 * @param {readonly (readonly [string, string])[]} names - From {@link readPropNames}
 * @param {string} version - The version of react-dom
 * @returns {string}
 */
export function render(names, version) {
	// The names are letters, digits, `:` and `-`: single quotes need no escape, and
	// they are what prettier writes, so the file is the same after it ran.
	const rows = names.map(([attribute, prop]) => `\t['${attribute}', '${prop}'],`);
	return `// @generated by scripts/generate-react-prop-names.mjs — do not edit by hand.
// Source: the possibleStandardNames of react-dom ${version} (cjs/react-dom-server.node.development.js).
// cspell:disable -- the names of HTML and SVG attributes, in lower case

/** \`[HTML attribute (lower case), React prop]\`, sorted by attribute. */
export const REACT_PROP_NAMES = [
${rows.join('\n')}
];
`;
}

if (process.argv[1] === import.meta.filename) {
	const source = readFileSync(
		path.join(dir, 'cjs', 'react-dom-server.node.development.js'),
		'utf8',
	);
	const version = JSON.parse(
		readFileSync(path.join(dir, 'package.json'), 'utf8'),
	).version;
	writeFileSync(output, render(readPropNames(source), version));
	console.log(`wrote ${path.relative(root, output)}`);
}
