/**
 * Generates `crates/kd_html/src/minify/tables.rs` from html-minifier-terser's
 * HTML parser: the character classes of an XML NCName (letters, digits,
 * combining characters, extenders), which decide where a tag name ends. The
 * name tests answer ASCII without searching the ranges, and a Rust test checks
 * that the shortcut agrees with the tables.
 *
 * Run it when html-minifier-terser is upgraded:
 * `node scripts/generate-minifier-tables.mjs`.
 * `scripts/generate-minifier-tables.spec.ts` fails while the committed table is
 * not what it writes, apart from the version in the header: that records the
 * html-minifier-terser the table was last generated from, so a release that
 * leaves the classes as they are passes without a regeneration.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { isMain } from './is-main.mjs';

const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, 'node_modules', 'html-minifier-terser');
const output = path.join(root, 'crates', 'kd_html', 'src', 'minify', 'tables.rs');

/**
 * Reads what the table is made from, out of `node_modules`.
 * @returns {{ source: string, version: string }} `src/htmlparser.js` and the version of
 * html-minifier-terser
 * @example
 * const { source, version } = readSources();
 */
export function readSources() {
	return {
		source: readFileSync(path.join(dir, 'src', 'htmlparser.js'), 'utf8'),
		version: JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8')).version,
	};
}

/**
 * Reads the string literal assigned to `const <name> = '...';`.
 * @param {string} source - `src/htmlparser.js`
 * @param {string} name - The constant's name
 * @returns {string} The regex source it holds (after JavaScript unescaping)
 */
function classSource(source, name) {
	const match = new RegExp(`const ${name} = '((?:[^'\\\\]|\\\\.)*)';`).exec(source);
	if (!match) {
		throw new Error(`${name} not found`);
	}
	// oxlint-disable-next-line typescript/no-implied-eval -- the string literal in the oracle's source text is evaluated to get the text it denotes
	return new Function(`return '${match[1]}';`)();
}

/**
 * Turns the inside of a regex character class into code point ranges.
 * @param {string} body - E.g. `A-Za-z\xC0-\xD6ı`
 * @returns {[number, number][]} The ranges, sorted and merged
 */
function ranges(body) {
	const tokens = [];
	const re = /\\u([\dA-Fa-f]{4})|\\x([\dA-Fa-f]{2})|\\(.)|(.)/gs;
	let m;
	while ((m = re.exec(body))) {
		if (m[1] !== undefined) {
			tokens.push({ cp: Number.parseInt(m[1], 16), dash: false });
		} else if (m[2] !== undefined) {
			tokens.push({ cp: Number.parseInt(m[2], 16), dash: false });
		} else if (m[3] === undefined) {
			tokens.push({ cp: m[4].codePointAt(0), dash: m[4] === '-' });
		} else {
			tokens.push({ cp: m[3].codePointAt(0), dash: false });
		}
	}
	const out = [];
	for (let i = 0; i < tokens.length; i++) {
		const t = tokens[i];
		if (tokens[i + 1]?.dash && tokens[i + 2]) {
			out.push([t.cp, tokens[i + 2].cp]);
			i += 2;
		} else {
			out.push([t.cp, t.cp]);
		}
	}
	out.sort((a, b) => a[0] - b[0]);
	return out;
}

/**
 * The text of `tables.rs`.
 * @param {string} source - `src/htmlparser.js`, from {@link readSources}
 * @param {string} version - The version of html-minifier-terser that the header names
 * @returns {string} The file, as committed (it needs no `cargo fmt`)
 * @example
 * const { source, version } = readSources();
 * const text = renderTables(source, version);
 */
export function renderTables(source, version) {
	const classes = ['combiningChar', 'digit', 'extender', 'letter'].map((name) => ({
		name,
		ranges: ranges(classSource(source, name)),
	}));
	const lines = [
		'// @generated by scripts/generate-minifier-tables.mjs — do not edit by hand.',
		`// Source: html-minifier-terser ${version} (src/htmlparser.js, the NCName character classes).`,
		'',
	];
	for (const { name, ranges: rs } of classes) {
		const rustName = name.replaceAll(/([A-Z])/g, '_$1').toUpperCase();
		lines.push(
			`pub static ${rustName}: [(u32, u32); ${rs.length}] = [`,
			...rs.map(([a, b]) => `\t(0x${a.toString(16)}, 0x${b.toString(16)}),`),
			'];',
			'',
		);
	}
	lines.push(
		'fn in_ranges(ranges: &[(u32, u32)], c: u32) -> bool {',
		'\tranges.iter().any(|&(lo, hi)| (lo..=hi).contains(&c))',
		'}',
		'',
		'/// `[letter_]`: where an NCName may start.',
		'#[must_use]',
		'pub fn is_name_start(c: char) -> bool {',
		'\t// ASCII is nearly all of it: skip the search through the ranges.',
		'\tif c.is_ascii() {',
		"\t\treturn c.is_ascii_alphabetic() || c == '_';",
		'\t}',
		'\tin_ranges(&LETTER, c as u32)',
		'}',
		'',
		'/// The rest of an NCName: letters, digits, `.`, `-`, `_`, combining marks, extenders.',
		'#[must_use]',
		'pub fn is_name_char(c: char) -> bool {',
		'\tif c.is_ascii() {',
		"\t\treturn c.is_ascii_alphanumeric() || matches!(c, '.' | '-' | '_');",
		'\t}',
		'\t// `.`, `-` and `_` are ASCII, so only the ranges remain.',
		'\tlet cp = c as u32;',
		'\tin_ranges(&LETTER, cp)',
		'\t\t|| in_ranges(&DIGIT, cp)',
		'\t\t|| in_ranges(&COMBINING_CHAR, cp)',
		'\t\t|| in_ranges(&EXTENDER, cp)',
		'}',
		'',
		'#[cfg(test)]',
		'mod tests {',
		'\tuse super::*;',
		'',
		'\t#[test]',
		'\tfn the_ascii_shortcuts_agree_with_the_tables() {',
		'\t\tfor cp in 0u32..128 {',
		'\t\t\tlet c = char::from_u32(cp).unwrap();',
		"\t\t\tlet start = c == '_' || in_ranges(&LETTER, cp);",
		"\t\t\tlet name = matches!(c, '.' | '-' | '_')",
		'\t\t\t\t|| in_ranges(&LETTER, cp)',
		'\t\t\t\t|| in_ranges(&DIGIT, cp)',
		'\t\t\t\t|| in_ranges(&COMBINING_CHAR, cp)',
		'\t\t\t\t|| in_ranges(&EXTENDER, cp);',
		'\t\t\tassert_eq!(is_name_start(c), start, "start {c:?}");',
		'\t\t\tassert_eq!(is_name_char(c), name, "char {c:?}");',
		'\t\t}',
		'\t}',
		'}',
		'',
	);
	return lines.join('\n');
}

/**
 * Writes the table of the installed html-minifier-terser.
 * @param {string} [out] - Where to write it
 * @example
 * generate(); // writes crates/kd_html/src/minify/tables.rs
 */
export function generate(out = output) {
	const { source, version } = readSources();
	writeFileSync(out, renderTables(source, version));
}

if (isMain(import.meta.filename)) {
	generate();
	process.stdout.write(`wrote ${path.relative(root, output)}\n`);
}
