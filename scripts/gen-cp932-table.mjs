/**
 * Writes `crates/kd_html/src/cp932_table.rs`: the two-byte part of Shift_JIS as Windows
 * (CP932) has it, read from the decoder that Node ships (WHATWG `shift_jis`), so that the
 * crate needs no dependency.
 *
 * ```sh
 * node scripts/gen-cp932-table.mjs
 * ```
 *
 * The table holds the code point of every `(lead, trail)` pair, 0 where there is none:
 * leads 0x81-0x9F and 0xE0-0xFC (60 of them), trails 0x40-0x7E and 0x80-0xFC (188 of them).
 * The index is `lead_index * 188 + trail_index`, which is the pointer of the WHATWG
 * encoding standard.
 */
import { writeFileSync } from 'node:fs';

const decoder = new TextDecoder('shift_jis');
const table = [];
for (let l = 0; l < 60; l++) {
	const lead = l < 31 ? 0x81 + l : 0xc1 + l;
	for (let t = 0; t < 188; t++) {
		const trail = t < 63 ? 0x40 + t : 0x41 + t;
		const text = decoder.decode(new Uint8Array([lead, trail]));
		const chars = [...text];
		table.push(chars.length === 1 && chars[0] !== '�' ? chars[0].codePointAt(0) : 0);
	}
}
if (table.some((c) => c > 0xff_ff)) {
	throw new Error('a code point outside the BMP');
}
const rows = [];
for (let i = 0; i < table.length; i += 12) {
	rows.push(
		'\t' +
			table
				.slice(i, i + 12)
				.map((c) => `0x${c.toString(16).toUpperCase().padStart(4, '0')}`)
				.join(', ') +
			',',
	);
}
const out = `//! The two-byte part of Windows Shift_JIS (CP932), generated by
//! \`scripts/gen-cp932-table.mjs\` from the decoder of Node (WHATWG \`shift_jis\`).
//! Do not edit by hand.

/// Leads \`0x81..=0x9F\` and \`0xE0..=0xFC\`: 60 of them.
pub(crate) const LEADS: usize = 60;
/// Trails \`0x40..=0x7E\` and \`0x80..=0xFC\`: 188 of them.
pub(crate) const TRAILS: usize = 188;

/// The code point of the pair at \`lead_index * TRAILS + trail_index\`, 0 for none.
pub(crate) static DOUBLE: [u16; LEADS * TRAILS] = [
${rows.join('\n')}
];
`;
writeFileSync(new URL('../crates/kd_html/src/cp932_table.rs', import.meta.url), out);
console.log(`${table.filter(Boolean).length} pairs`);
