/**
 * Generates `crates/kd_js/src/jsx_entities.rs`: the named character
 * references that JSX text and attribute strings decode. JSX knows only a
 * fixed list (HTML 4 plus `apos`), not the 2000+ names of HTML5; which names
 * are in the list is found by asking esbuild (the compiler v2 used) about
 * every candidate name, so the table is exactly what v2 decoded.
 *
 * The esbuild asked is `esbuild-v2`, the version the published v2 jsx-compiler
 * pins (an alias: `docs/v3/development.md`, "v2 の oracle"; the root `esbuild`
 * is the runtime's).
 *
 * Run it when `esbuild-v2` is changed: `node scripts/generate-jsx-entities.mjs`.
 * `scripts/generate-jsx-entities.spec.ts` fails while the committed table is not
 * what it writes.
 */
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { transformSync, version as esbuildVersion } from 'esbuild-v2';

const root = path.resolve(import.meta.dirname, '..');

/**
 * Reads what the table is made from: the candidate names (the WHATWG table of
 * `kd_html`) and the version of the esbuild that is asked about them.
 * @returns {{ names: string[], version: string }} The names as the WHATWG table
 * of `kd_html` spells them (without `&` and `;`), and the installed version of
 * `esbuild-v2`
 * @example
 * readSources().version; // what package.json declares for `esbuild-v2`
 */
export function readSources() {
	const tableSource = readFileSync(
		path.join(root, 'crates', 'kd_html', 'src', 'entities_table.rs'),
		'utf8',
	);
	const names = [...tableSource.matchAll(/^\t\("([A-Z0-9]+)", "/gim)].map((m) => m[1]);
	if (names.length < 2000) {
		throw new Error(`expected the WHATWG table, found ${names.length} names`);
	}
	return { names, version: esbuildVersion };
}

/**
 * The table of `jsx_entities.rs`.
 * @param {{ names: string[], version: string }} sources - From `readSources`
 * @returns {{ text: string, count: number }} The file, and how many names JSX decodes
 * @example
 * renderJsxEntities({ names: ['amp', 'AMP', 'nbsp'], version: 'x' }).count; // 2 (JSX does not know `AMP`)
 */
export function renderJsxEntities({ names, version }) {
	/** @type {[string, string][]} */
	const decoded = [];
	for (const name of names) {
		const out = transformSync(`x = <a>&${name};</a>`, {
			loader: 'jsx',
			jsx: 'transform',
			charset: 'utf8',
		}).code;
		const match =
			/createElement\("a", null, ("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')\)/.exec(out);
		if (!match) {
			throw new Error(`unexpected esbuild output for ${name}: ${out}`);
		}
		const text = new Function(`return ${match[1]}`)();
		if (text !== `&${name};`) {
			decoded.push([name, text]);
		}
	}
	decoded.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

	const rustString = (text) =>
		`"${[...text].map((c) => `\\u{${c.codePointAt(0).toString(16)}}`).join('')}"`;
	const lines = [
		'// @generated by scripts/generate-jsx-entities.mjs — do not edit by hand.',
		`// Source: esbuild ${version} (the named references its JSX parser decodes).`,
		'',
		'/// Named references (without `&` and `;`) that JSX decodes, sorted by name.',
		`pub static DECODE: [(&str, &str); ${decoded.length}] = [`,
		...decoded.map(([name, text]) => `\t("${name}", ${rustString(text)}),`),
		'];',
		'',
		'/// The replacement text of `&name;`.',
		'#[must_use]',
		"pub fn named(name: &str) -> Option<&'static str> {",
		'\tDECODE',
		'\t\t.binary_search_by(|(n, _)| (*n).cmp(name))',
		'\t\t.ok()',
		'\t\t.map(|i| DECODE[i].1)',
		'}',
		'',
	];
	return { text: lines.join('\n'), count: decoded.length };
}

/**
 * Whether Node was started with this file. Node resolves the main module
 * through symbolic links while `argv[1]` keeps the path as given; a runner or
 * `--eval` has no path of a file that exists.
 * @returns {boolean} Whether this is the script that runs
 */
function isMain() {
	try {
		return realpathSync(process.argv[1]) === import.meta.filename;
	} catch {
		return false;
	}
}

if (isMain()) {
	const { text, count } = renderJsxEntities(readSources());
	const out = path.join(root, 'crates', 'kd_js', 'src', 'jsx_entities.rs');
	writeFileSync(out, text);
	process.stdout.write(`wrote ${path.relative(root, out)}: ${count} names\n`);
}
