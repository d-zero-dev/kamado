/**
 * Generates `crates/kd_js/src/jsx_entities.rs`: the named character
 * references that JSX text and attribute strings decode. JSX knows only a
 * fixed list (HTML 4 plus `apos`), not the 2000+ names of HTML5; which names
 * are in the list is found by asking esbuild (the compiler v2 used) about
 * every candidate name, so the table is exactly what v2 decoded.
 * Run it when esbuild is upgraded: `node scripts/generate-jsx-entities.mjs`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { transformSync, version } from 'esbuild';

const root = path.resolve(import.meta.dirname, '..');
const tableSource = readFileSync(
	path.join(root, 'crates', 'kd_html', 'src', 'entities_table.rs'),
	'utf8',
);
const names = [...tableSource.matchAll(/^\t\("([A-Z0-9]+)", "/gim)].map((m) => m[1]);
if (names.length < 2000) {
	throw new Error(`expected the WHATWG table, found ${names.length} names`);
}

/** @type {[string, string][]} */
const decoded = [];
for (const name of names) {
	const out = transformSync(`x = <a>&${name};</a>`, {
		loader: 'jsx',
		jsx: 'transform',
		charset: 'utf8',
	}).code;
	const match = /createElement\("a", null, ("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')\)/.exec(
		out,
	);
	if (!match) {
		throw new Error(`unexpected esbuild output for ${name}: ${out}`);
	}
	const text = new Function(`return ${match[1]}`)();
	if (text !== `&${name};`) {
		decoded.push([name, text]);
	}
}
decoded.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const rustString = (text) =>
	`"${[...text].map((c) => `\\u{${c.codePointAt(0).toString(16)}}`).join('')}"`;
const lines = [
	'// @generated by scripts/generate-jsx-entities.mjs — do not edit by hand.',
	`// Source: esbuild ${version} (the named references its JSX parser decodes).`,
	'',
	'/// Named references (without `&` and `;`) that JSX decodes, sorted by name.',
	`pub static DECODE: [(&str, &str); ${decoded.length}] = [`,
	...decoded.map(([name, text]) => `\t("${name}", ${rustString(text)}),`),
	'];',
	'',
	'/// The replacement text of `&name;`.',
	'#[must_use]',
	"pub fn named(name: &str) -> Option<&'static str> {",
	'\tDECODE',
	'\t\t.binary_search_by(|(n, _)| (*n).cmp(name))',
	'\t\t.ok()',
	'\t\t.map(|i| DECODE[i].1)',
	'}',
	'',
];
const out = path.join(root, 'crates', 'kd_js', 'src', 'jsx_entities.rs');
writeFileSync(out, lines.join('\n'));
process.stdout.write(`wrote ${path.relative(root, out)}: ${decoded.length} names\n`);
