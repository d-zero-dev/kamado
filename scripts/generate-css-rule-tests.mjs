/**
 * Writes `crates/kd_css/tests/rules.rs`: one test per rule family of the
 * hand-written cases (`css-golden-cases.mjs`), each case with what cssnano
 * (kamado v2's options) makes of it, so that the expected strings are
 * cssnano's and not guesses. A case where `kd_css` deliberately gives
 * another answer is listed in `tests/common/mod.rs` with both answers.
 * Run it when cssnano is upgraded: `node scripts/generate-css-rule-tests.mjs`.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';

import { cssnanoMinify } from './css-oracle.mjs';
import { cssCaseGroups } from './css-golden-cases.mjs';

const root = path.resolve(import.meta.dirname, '..');

/**
 * Writes a Rust string literal.
 * @param {string} text - The text
 * @returns {string} The literal
 */
function rustString(text) {
	let out = '"';
	for (const c of text) {
		const code = c.codePointAt(0) ?? 0;
		if (c === '"') {
			out += String.raw`\"`;
		} else if (c === '\\') {
			out += String.raw`\\`;
		} else if (c === '\n') {
			out += String.raw`\n`;
		} else if (c === '\r') {
			out += String.raw`\r`;
		} else if (c === '\t') {
			out += String.raw`\t`;
		} else if (code < 0x20 || code === 0x7f || /[\p{C}\p{Z}]/u.test(c) && c !== ' ') {
			out += `\\u{${code.toString(16)}}`;
		} else {
			out += c;
		}
	}
	return `${out}"`;
}

const groups = cssCaseGroups();
let out = `//! Generated by \`scripts/generate-css-rule-tests.mjs\`; do not edit.\n//!\n`;
out += `//! Every case is a style sheet and what cssnano makes of it. \`kd_css\` must give\n`;
out += `//! the same, unless the case is listed in \`common::DELIBERATE\` with both\n`;
out += `//! answers.\n\nmod common;\n\n`;
const names = new Set();
for (const [family, cases] of Object.entries(groups)) {
	const name = family.replaceAll(/[^a-z]+/gu, '_').replaceAll(/^_|_$/gu, '');
	if (names.has(name)) {
		throw new Error(`duplicate family name ${name}`);
	}
	names.add(name);
	out += `#[test]\nfn ${name}() {\n\tcommon::check_all(&[\n`;
	for (const input of cases) {
		let expected;
		try {
			expected = await cssnanoMinify(input);
		} catch {
			expected = '__ERROR__';
		}
		out += `\t\t(${rustString(input)}, ${rustString(expected)}),\n`;
	}
	out += `\t]);\n}\n\n`;
}
writeFileSync(path.join(root, 'crates', 'kd_css', 'tests', 'rules.rs'), out.trimEnd() + '\n');
process.stdout.write(`wrote ${names.size} families\n`);
